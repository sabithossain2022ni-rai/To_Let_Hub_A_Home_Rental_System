package com.tolet.ui;

import com.tolet.data.DataStore;
import com.tolet.model.*;

import javax.swing.*;
import java.awt.Component;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

/** Generates a printable agreement / receipt text file for approved requests. */
public final class Documents {
    private Documents() {}

    public static void save(Component parent, Booking b) {
        DataStore db = DataStore.get();
        Property p = db.property(b.propertyId);
        User owner = db.user(p.ownerId), cust = db.user(b.customerId);
        String line = "============================================================\n";
        StringBuilder s = new StringBuilder(line);
        boolean rent = b.kind == Booking.Kind.RENT_REQUEST;
        s.append(rent ? "          RESIDENTIAL RENT AGREEMENT (DEMO)\n" : "          PROPERTY SALE CONFIRMATION (DEMO)\n").append(line);
        s.append("Reference : ").append(b.id).append("\nDate      : ").append(Ui.day(System.currentTimeMillis())).append("\n\n");
        s.append(rent ? "LANDLORD  : " : "SELLER    : ").append(owner.name).append("  (").append(owner.phone).append(")\n");
        s.append(rent ? "TENANT    : " : "BUYER     : ").append(cust.name).append("  (").append(cust.phone).append(")\n\n");
        s.append("PROPERTY\n  ").append(p.title).append("\n  ").append(p.address).append(", ").append(p.location()).append("\n  ")
                .append(p.type.label()).append(", ").append(p.bedrooms).append(" bed, ").append(p.bathrooms).append(" bath, ").append(p.sqft).append(" sqft\n\n");
        if (rent) {
            s.append("TERMS\n  1. Monthly rent        : ").append(Ui.money(b.offer)).append("\n  2. Security deposit    : ").append(Ui.money(b.offer * 2))
                    .append(" (refundable)\n  3. Move-in date        : ").append(b.date).append("\n  4. Duration            : 12 months, renewable\n")
                    .append("  5. Rent is due before the 5th of each month.\n  6. Utility bills are paid by the tenant.\n  7. Either party may end the agreement with 60 days notice.\n");
        } else {
            s.append("TERMS\n  1. Agreed price        : ").append(Ui.money(b.offer)).append("\n  2. Preferred handover  : ").append(b.date)
                    .append("\n  3. Booking money (10%) : ").append(Ui.money(b.offer * 0.10)).append("\n  4. Registration and legal transfer to follow with a lawyer.\n");
        }
        s.append("\nSignatures:\n\n  ____________________            ____________________\n  ").append(owner.name).append("                      ").append(cust.name)
                .append("\n\nThis is a demo document generated by ToLet Hub and has no legal standing.\n");
        JFileChooser fc = new JFileChooser();
        fc.setSelectedFile(new File((rent ? "rent-agreement-" : "sale-confirmation-") + b.id + ".txt"));
        if (fc.showSaveDialog(parent) == JFileChooser.APPROVE_OPTION) {
            try { Files.write(fc.getSelectedFile().toPath(), s.toString().getBytes(StandardCharsets.UTF_8)); Ui.msg(parent, "Saved to " + fc.getSelectedFile().getName()); }
            catch (IOException e) { Ui.error(parent, "Could not save file: " + e.getMessage()); }
        }
    }
}
